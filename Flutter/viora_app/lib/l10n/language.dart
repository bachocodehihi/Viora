  String translate(String key) {
    String locale = 'en';
    try {
      locale = Localizations.localeOf(context).languageCode;
    } catch (_) {}
    final keys = _localizedValues[locale] ?? _localizedValues['en']!;
    return keys[key] ?? key;
  }

  String errorFromCode(dynamic code, {String? fallbackMessage}) {
    if (code == null) {
      return fallbackMessage ?? serverError;
    }
    final codeStr = code.toString().trim();
    if (codeStr.isEmpty) {
      return fallbackMessage ?? serverError;
    }
    String locale = 'en';
    try {
      locale = Localizations.localeOf(context).languageCode;
    } catch (_) {}
    final keys = _localizedValues[locale] ?? _localizedValues['en']!;
    if (keys.containsKey(codeStr)) {
      return keys[codeStr]!;
    }
    final lowerKey = codeStr.toLowerCase();
    if (keys.containsKey(lowerKey)) {
      return keys[lowerKey]!;
    }
    return fallbackMessage ?? serverError;
  }

  static final Map<String, Map<String, String>> _localizedValues = {
    'en': appEn,
    'vi': appVi,
  };

  static String translateStatic(String key, {String? localeCode}) {
    final code = localeCode ?? LanguageManager.localeNotifier.value.languageCode;
    final keys = _localizedValues[code] ?? _localizedValues['en']!;
    return keys[key] ?? key;
  }

  static Set<String> getAllTranslationsOf(String key) {
    final result = <String>{};
    for (final map in _localizedValues.values) {
      final val = map[key];
      if (val != null && val.trim().isNotEmpty) {
        result.add(val.trim());
      }
    }
    return result;
  }

  static bool isImagePlaceholder(String? text) {
    if (text == null) return true;
    final clean = text.trim();
    if (clean.isEmpty) return true;
    final lower = clean.toLowerCase();
    if (lower == 'image' || lower == 'images' || lower == 'photo' || lower == 'photos') return true;
    if (clean.startsWith('📷 [') || clean.startsWith('http://') || clean.startsWith('https://')) return true;

    for (final trans in getAllTranslationsOf('imageCaptionOnly')) {
      if (lower == trans.toLowerCase()) return true;
    }
    for (final trans in getAllTranslationsOf('imageCaptionPlaceholder')) {
      if (clean == trans || lower == trans.toLowerCase()) return true;
    }
    return false;
  }

  static bool isAnonymousMemberName(String? name) {
    if (name == null || name.trim().isEmpty) return false;
    final lower = name.trim().toLowerCase();
    for (final map in _localizedValues.values) {
      final anon = map['anonymousMember']?.trim().toLowerCase();
      if (anon != null && anon.isNotEmpty) {
        if (lower.startsWith(anon)) return true;
      }
    }
    return false;
  }

  static bool hasYouIndicator(String? text) {
    if (text == null || text.trim().isEmpty) return false;
    final lower = text.toLowerCase();
    for (final map in _localizedValues.values) {
      final you = map['you']?.trim().toLowerCase();
      if (you != null && you.isNotEmpty && lower.contains('($you)')) {
        return true;
      }
    }
    return false;
  }

  static bool isAnonymousMention(String mention) {
    if (!mention.startsWith('@')) return false;
    final withoutAt = mention.substring(1).trim().toLowerCase();
    for (final map in _localizedValues.values) {
      final anon = map['anonymousMember']?.trim().toLowerCase();
      if (anon != null && anon.isNotEmpty) {
        if (withoutAt.startsWith(anon)) return true;
      }
    }
    return false;
  }

  static String getLocalizedMentionDisplay(String rawMention, Language currentL10n) {
    if (isAnonymousMention(rawMention)) {
      final hasYou = hasYouIndicator(rawMention);
      if (hasYou) {
        return '@${currentL10n.anonymousMember} (${currentL10n.you})';
      } else {
        return '@${currentL10n.anonymousMember}';
      }
    }
    return rawMention;
  }

  static RegExp getCommentMentionRegex() {
    final anonNames = getAllTranslationsOf('anonymousMember');
    final youNames = getAllTranslationsOf('you');

    final escapedAnon = anonNames.map((n) {
      return RegExp.escape(n).replaceAll(r'\ ', r'\s+');
    }).toList();

    final escapedYou = youNames.map(RegExp.escape).toList();
    escapedYou.addAll(['You', 'Bạn']);
    final youPattern = escapedYou.toSet().join('|');

    final anonPattern = escapedAnon.isNotEmpty
        ? '(?:${escapedAnon.join('|')})(?:\\s*\\((?:$youPattern)\\))?'
        : r'Anonymous\s+Member';

    return RegExp(
      '(@$anonPattern|@[a-zA-Z0-9_\\.\\u00C0-\\u024F\\u1E00-\\u1EFF]+)',
      caseSensitive: false,
    );
  }
