class LanguageManager {
  static final ValueNotifier<Locale> localeNotifier = ValueNotifier<Locale>(const Locale('vi'));
  static const String _storageKey = 'language_code';
  static SharedPreferences? _prefs;

  static Future<void> init() async {
    try {
      _prefs = await SharedPreferences.getInstance();
      final String? savedLanguage = _prefs?.getString(_storageKey);
      if (savedLanguage != null) {
        localeNotifier.value = Locale(savedLanguage);
      }
    } catch (e) {
      debugPrint('Error initializing LanguageManager: $e');
    }
  }

  static void changeLanguage(String languageCode) {
    localeNotifier.value = Locale(languageCode);
    _prefs?.setString(_storageKey, languageCode);
  }

  static bool isEnglish() {
    return localeNotifier.value.languageCode == 'en';
  }
}

